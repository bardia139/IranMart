PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS sources (
  slug TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  group_name TEXT NOT NULL,
  integration TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'awaiting_authorized_access',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS offers (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  source_slug TEXT NOT NULL REFERENCES sources(slug),
  external_id TEXT NOT NULL,
  title TEXT NOT NULL,
  category TEXT,
  price REAL,
  currency TEXT NOT NULL DEFAULT 'IRR' CHECK(currency IN ('IRR','IRT')),
  seller_name TEXT,
  product_url TEXT NOT NULL,
  image_url TEXT,
  availability TEXT,
  condition TEXT NOT NULL DEFAULT 'unknown' CHECK(condition IN ('new','used','unknown')),
  observed_at TEXT NOT NULL,
  UNIQUE(source_slug, external_id)
);
CREATE INDEX IF NOT EXISTS offers_title_idx ON offers(title);
CREATE INDEX IF NOT EXISTS offers_source_idx ON offers(source_slug);
CREATE INDEX IF NOT EXISTS offers_price_idx ON offers(price);
